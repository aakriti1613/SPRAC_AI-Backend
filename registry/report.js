// Library status report (docs/LIBRARY_STATUS.md): progress against the V1
// target, what each source contributed, and the "cleaning" findings.
// No timestamps, so the file only changes when the catalogue changes.
import { libraryTargets, loadBlueprints } from "../sparc/index.js";
import { STYLE_LEVEL_IDS, STYLE_LEVELS } from "../sparc/styleLevels.js";

const cell = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");

export function renderLibraryStatus(records, blueprints = loadBlueprints()) {
  const targets = libraryTargets(blueprints);
  const verified = records.filter((r) => r.trust === "verified" && r.kind === "component");
  const has = (room, level) => verified.some((r) => r.room === room && r.styleLevel === level);
  const needed = targets.rows.flatMap((row) => row.levels.map((level) => ({ room: row.room, level })));
  const done = needed.filter((n) => has(n.room, n.level)).length;

  const L = [];
  L.push("<!-- AUTO-GENERATED by `npm run registry:report`. Do not edit by hand. -->");
  L.push("# SPARC AI — Component library status");
  L.push("");
  L.push(`**V1 progress: ${done} / ${targets.total} room-and-level slots have a verified component** (${Math.round((done / targets.total) * 100)}%).`);
  L.push("");
  L.push("Only our own library can produce `verified` components. Everything from other sources is a `candidate`:");
  L.push("searchable and recommendable, never placed into a build automatically.");
  L.push("");

  L.push("## By source");
  L.push("");
  L.push("| Source | Total | Verified | Candidate | Deprecated |");
  L.push("|---|---|---|---|---|");
  const sources = [...new Set(records.map((r) => r.source))].sort();
  for (const s of sources) {
    const rs = records.filter((r) => r.source === s);
    const n = (t) => rs.filter((r) => r.trust === t).length;
    L.push(`| ${s} | ${rs.length} | ${n("verified")} | ${n("candidate")} | ${n("deprecated")} |`);
  }
  L.push(`| **all** | **${records.length}** | **${records.filter((r) => r.trust === "verified").length}** | **${records.filter((r) => r.trust === "candidate").length}** | **${records.filter((r) => r.trust === "deprecated").length}** |`);
  L.push("");

  L.push("## Coverage of V1 targets (✅ verified · ⬜ still needed · — not required)");
  L.push("");
  L.push(`| Room | ${STYLE_LEVEL_IDS.map((l) => STYLE_LEVELS[l].label).join(" | ")} |`);
  L.push(`|---|${STYLE_LEVEL_IDS.map(() => "---").join("|")}|`);
  for (const row of targets.rows) {
    L.push(`| ${row.room} | ${STYLE_LEVEL_IDS.map((l) => (!row.levels.includes(l) ? "—" : has(row.room, l) ? "✅" : "⬜")).join(" | ")} |`);
  }
  L.push("");

  const legacy = records.filter((r) => r.source === "own-templates");
  if (legacy.length) {
    const count = (re) => legacy.filter((r) => r.problems.some((p) => re.test(p))).length;
    L.push("## Old template code (clone-and-own) — what cleaning it needs");
    L.push("");
    L.push(`${legacy.length} components from the prototype's templates were analysed:`);
    L.push("");
    L.push(`- ${count(/^contract:/)} do not fit their room's plug shape`);
    L.push(`- ${count(/^fixed-colour/)} hard-code colours instead of theme tokens`);
    L.push(`- ${count(/config singleton/)} read a global config instead of taking props`);
    L.push(`- ${legacy.filter((r) => !r.room).length} are UI primitives with no room of their own`);
    L.push("");
  }

  const external = records.filter((r) => ["npm", "github", "storybook", "shadcn", "magicui", "aceternity"].includes(r.source) && r.room);
  if (external.length) {
    L.push("## External candidates per room (top 3 by popularity)");
    L.push("");
    L.push("| Room | Candidates |");
    L.push("|---|---|");
    const rooms = [...new Set(external.map((r) => r.room))].sort();
    const score = (r) => r.quality?.downloads ?? (r.quality?.stars ?? 0) * 100;
    for (const room of rooms) {
      const top = external
        .filter((r) => r.room === room)
        .sort((a, b) => score(b) - score(a) || a.slug.localeCompare(b.slug))
        .slice(0, 3)
        .map((r) => `${r.name} (${r.source}${r.quality?.downloads ? `, ${Math.round(r.quality.downloads / 1000)}k/month` : ""})`);
      L.push(`| ${room} | ${cell(top.join(" · "))} |`);
    }
    L.push("");
  }

  const exceptions = records.flatMap((r) => (r.exceptions ?? []).map((e) => ({ ...e, slug: r.slug })));
  if (exceptions.length) {
    L.push("## Reviewed rule exceptions");
    L.push("");
    for (const e of exceptions) L.push(`- \`${e.slug}\` — ${e.rule}: ${e.reason}`);
    L.push("");
  }

  const ownProblems = records.filter((r) => r.source === "own-library" && r.trust !== "verified");
  L.push("## Own components that are not verified");
  L.push("");
  if (!ownProblems.length) L.push("None — every component in sparc-ui/library passes every check.");
  for (const r of ownProblems) L.push(`- \`${r.slug}\` (${r.trust}): ${r.problems.join("; ")}`);
  L.push("");
  return L.join("\n");
}

// Assemble a self-contained, buildable project from a validated SPARC config.
//
// It copies the shared code (core, library, contracts, theme, blueprints) and the
// right shell (portal or site) into one folder, writes src/sparc.config.json and
// a sparc.lock.json (exactly which component version fills each room). The result
// builds on its own with Vite.
//
// Output goes under sparc-ui/.generated/<name> so the build reuses sparc-ui's
// installed dependencies (no per-project npm install needed for local verifying).
// For a real deploy the folder is copied out and `npm install` is run there.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { checkSparcConfig } from "../../sparc/config.js";
import { composeSite, lockFromComposition } from "../retrieve/compose.js";

const BACKEND = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const SPARC_UI = path.join(BACKEND, "sparc-ui");
export const GENERATED_DIR = path.join(SPARC_UI, ".generated");

const SHELL_FOR = { "admin-portal": "portal-shell", portfolio: "site-shell", landing: "site-shell", ecommerce: "site-shell", booking: "site-shell" };

// Runtime + build dependencies a generated project declares (versions copied from sparc-ui).
const RUNTIME_DEPS = ["react", "react-dom", "react-router-dom", "@supabase/supabase-js", "zod", "lucide-react", "clsx", "tailwind-merge", "motion"];
const DEV_DEPS = ["vite", "@vitejs/plugin-react", "tailwindcss", "@tailwindcss/vite", "typescript", "@types/react", "@types/react-dom"];

function depVersions() {
  const pkg = JSON.parse(fs.readFileSync(path.join(SPARC_UI, "package.json"), "utf8"));
  const all = { ...pkg.dependencies, ...pkg.devDependencies };
  const pick = (names) => Object.fromEntries(names.map((n) => [n, all[n] || "latest"]));
  return { dependencies: pick(RUNTIME_DEPS), devDependencies: pick(DEV_DEPS) };
}

const VITE_CONFIG = `import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";
import tailwindcss from "@tailwindcss/vite";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.dirname(fileURLToPath(import.meta.url));
// GENERATED by SPARC AI. Self-contained: all shared code lives under src/_sparc.
export default defineConfig({
  base: "/",
  plugins: [react(), tailwindcss()],
  resolve: {
    alias: {
      "@core": path.join(dir, "src/_sparc/core"),
      "@library": path.join(dir, "src/_sparc/library"),
      "@contracts": path.join(dir, "src/_sparc/contracts/rooms.d.ts"),
      "@blueprints": path.join(dir, "src/_sparc/blueprints"),
    },
    dedupe: ["react", "react-dom"],
  },
  build: { outDir: "dist", emptyOutDir: true, chunkSizeWarningLimit: 1100 },
});
`;

const TSCONFIG = JSON.stringify(
  {
    compilerOptions: {
      target: "ES2022",
      lib: ["ES2022", "DOM", "DOM.Iterable"],
      module: "ESNext",
      moduleResolution: "bundler",
      jsx: "react-jsx",
      types: ["vite/client"],
      resolveJsonModule: true,
      allowImportingTsExtensions: true,
      verbatimModuleSyntax: true,
      noEmit: true,
      skipLibCheck: true,
      strict: true,
      baseUrl: ".",
      paths: { "@core/*": ["./src/_sparc/core/*"], "@library/*": ["./src/_sparc/library/*"], "@contracts": ["./src/_sparc/contracts/rooms.d.ts"], "@blueprints/*": ["./src/_sparc/blueprints/*"] },
    },
    include: ["src"],
  },
  null,
  2
);

const INDEX_CSS = `@import "tailwindcss";
@import "./_sparc/theme/sparc.css";

@source "./_sparc/library";
@source "./_sparc/core";
@source "./";
`;

const indexHtml = (title) => `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>${String(title).replace(/[<>&]/g, "")}</title>
  </head>
  <body>
    <div id="root"></div>
    <script type="module" src="/src/main.tsx"></script>
  </body>
</html>
`;

function copyDir(from, to) {
  fs.cpSync(from, to, { recursive: true });
}

/** Copy the shell's own src files (everything except its registries + sample configs, which we handle). */
const LEVEL_ORDER = ["basic", "good", "amazing", "astonishing"];

/** The registry file a site of this style level uses: its own, or the closest lower one the shell has. */
export function registryFor(shell, styleLevel) {
  const dir = path.join(SPARC_UI, "shells", shell, "src", "registries");
  for (let i = LEVEL_ORDER.indexOf(styleLevel); i >= 0; i -= 1) {
    if (fs.existsSync(path.join(dir, `${LEVEL_ORDER[i]}.ts`))) return `${LEVEL_ORDER[i]}.ts`;
  }
  throw new Error(`${shell} has no registry at or below "${styleLevel}"`);
}

function copyShellSrc(shell, destSrc, styleLevel) {
  const srcDir = path.join(SPARC_UI, "shells", shell, "src");
  for (const entry of fs.readdirSync(srcDir, { withFileTypes: true })) {
    if (entry.name === "index.css" || entry.name === "sparc.config.json") continue;
    if (entry.name === "configs") continue; // sample configs, not for a generated site
    const from = path.join(srcDir, entry.name);
    const to = path.join(destSrc, entry.name);
    if (entry.name === "registries") {
      // Only this site's style level (the others would be dead code that still gets built and shipped).
      const file = registryFor(shell, styleLevel);
      fs.mkdirSync(to, { recursive: true });
      fs.copyFileSync(path.join(from, file), path.join(to, file));
    } else if (entry.isDirectory()) copyDir(from, to);
    else fs.copyFileSync(from, to);
  }
}

/**
 * assembleProject(config, { name, records, outDir?, lock? })
 * Returns { ok, dir, lock, errors }.
 */
export function assembleProject(config, { name, records = [], outDir = GENERATED_DIR, lock: providedLock } = {}) {
  const check = checkSparcConfig(config);
  if (!check.ok) return { ok: false, errors: check.errors };
  if (!/^[a-z0-9][a-z0-9-]*$/.test(String(name || ""))) return { ok: false, errors: ["name must be a lowercase slug"] };

  const shell = SHELL_FOR[config.websiteType];
  const enabledOptional = config.rooms?.enabled || [];
  const composition = composeSite(records, { websiteType: config.websiteType, styleLevel: config.styleLevel, enabledOptional });
  const lock = providedLock || { ...lockFromComposition(composition), config: { brand: config.brand.name, industry: config.industry }, generatedAt: new Date().toISOString(), reuse: { components: Object.keys(composition.picks).length, newCode: 0 } };

  const dir = path.join(outDir, name);
  fs.rmSync(dir, { recursive: true, force: true });
  const src = path.join(dir, "src");
  const shared = path.join(src, "_sparc");
  fs.mkdirSync(shared, { recursive: true });

  // 1. Shared code.
  copyDir(path.join(SPARC_UI, "core"), path.join(shared, "core"));
  copyDir(path.join(SPARC_UI, "library"), path.join(shared, "library"));
  copyDir(path.join(SPARC_UI, "contracts"), path.join(shared, "contracts"));
  copyDir(path.join(SPARC_UI, "theme"), path.join(shared, "theme"));
  fs.mkdirSync(path.join(shared, "blueprints"), { recursive: true });
  for (const file of fs.readdirSync(path.join(BACKEND, "sparc", "blueprints"))) {
    if (file.endsWith(".json")) fs.copyFileSync(path.join(BACKEND, "sparc", "blueprints", file), path.join(shared, "blueprints", file));
  }

  // 2. Shell src + config + css.
  copyShellSrc(shell, src, config.styleLevel);
  fs.writeFileSync(path.join(src, "sparc.config.json"), `${JSON.stringify(config, null, 2)}\n`);
  fs.writeFileSync(path.join(src, "index.css"), INDEX_CSS);

  // 3. Project root files.
  const { dependencies, devDependencies } = depVersions();
  const pkg = {
    name,
    private: true,
    version: "1.0.0",
    type: "module",
    description: `${config.brand.name} — generated by SPARC AI`,
    scripts: { dev: "vite", build: "vite build", preview: "vite preview" },
    dependencies,
    devDependencies,
  };
  fs.writeFileSync(path.join(dir, "package.json"), `${JSON.stringify(pkg, null, 2)}\n`);
  fs.writeFileSync(path.join(dir, "vite.config.ts"), VITE_CONFIG);
  fs.writeFileSync(path.join(dir, "tsconfig.json"), `${TSCONFIG}\n`);
  fs.writeFileSync(path.join(dir, "index.html"), indexHtml(config.brand.name));
  fs.writeFileSync(path.join(dir, "sparc.lock.json"), `${JSON.stringify(lock, null, 2)}\n`);
  fs.writeFileSync(path.join(dir, ".gitignore"), "node_modules\ndist\n.env\n.env.local\n");
  fs.writeFileSync(path.join(dir, "README.md"), `# ${config.brand.name}\n\nGenerated by SPARC AI from a ${config.styleLevel} ${config.websiteType}.\n\n\`\`\`bash\nnpm install\nnpm run dev      # work on it\nnpm run build    # make dist/ to deploy\n\`\`\`\n\nWhich component fills each room is recorded in \`sparc.lock.json\`.\n`);

  return { ok: true, dir, lock, composition, errors: [] };
}

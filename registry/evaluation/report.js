// Turns docs/eval/results.json into docs/EVALUATION.md (tables, easy English) and
// docs/eval/charts.html (one self-contained page of bar charts). Pure functions.
import { mean, median, pct, round, summarize } from "./metrics.js";

export const SYSTEM_LABELS = {
  templates: "(a) Templates only",
  "sparc-offline": "(b) SPARC, no AI key",
  "sparc-gemini": "(b) SPARC + Gemini planner",
  "ai-code": "(c) AI writes all the code",
};
const ORDER = ["templates", "sparc-offline", "sparc-gemini", "ai-code"];
export const COVER_MIN = 0.6; // a site "covers" a request when it mentions at least 60% of the request's key words

/** The rows of one system, as an array. */
export function rowsOf(results, system) {
  if (system === "templates") return Object.values(results.templates ?? {});
  if (system === "ai-code") return Object.values(results.ai ?? {});
  const engine = system.replace("sparc-", "");
  return Object.values(results.sparc?.[engine] ?? {});
}

/** A request is fully served when the system's own checks pass AND the key words appear. */
export const covered = (system, r) => (system === "templates" ? r.ok === true : r.ok === true && (r.keywordCoverage ?? 0) >= COVER_MIN);

export function aggregate(results) {
  const systems = ORDER.filter((s) => rowsOf(results, s).length);
  const rows = {};
  for (const s of systems) {
    const rs = rowsOf(results, s);
    const built = rs.filter((r) => r.gzipKb !== undefined);
    rows[s] = {
      label: SYSTEM_LABELS[s],
      n: rs.length,
      ownChecksPct: pct(rs, (r) => r.ok === true),
      buildsPct: s === "templates" ? null : pct(rs, (r) => r.buildOk === true),
      coveredPct: pct(rs, (r) => covered(s, r)),
      typeCorrectPct: s.startsWith("sparc") ? pct(rs, (r) => r.typeCorrect === true) : null,
      avgSeconds: round(mean(rs.map((r) => (r.totalMs ?? 0) / 1000)), 1),
      avgTokens: Math.round(mean(rs.map((r) => r.tokens?.total ?? 0))),
      avgNewLines: Math.round(mean(rs.map((r) => (r.newCodeLines ?? 0) + (r.newConfigLines ?? 0)))),
      avgNewCodeLines: Math.round(mean(rs.map((r) => r.newCodeLines ?? 0))),
      avgReusePct: round(mean(rs.map((r) => r.reusePct ?? 0)), 1),
      findingsPerSite: round(mean(rs.map((r) => r.scan?.total ?? 0)), 2),
      sitesWithFindings: pct(rs.filter((r) => r.scan), (r) => r.scan.total > 0),
      kindsTotal: rs.reduce((acc, r) => {
        for (const [k, v] of Object.entries(r.scan?.byKind ?? {})) acc[k] = (acc[k] ?? 0) + v;
        return acc;
      }, {}),
      gzipKb: summarize(built.map((r) => r.gzipKb)),
      fallbacks: rs.filter((r) => r.fallback).length,
    };
  }

  const types = [...new Set(Object.values(results.templates ?? {}).map((r) => r.type))];
  const byType = {};
  for (const t of types) {
    byType[t] = { n: Object.values(results.templates).filter((r) => r.type === t).length };
    for (const s of systems) {
      const rs = rowsOf(results, s).filter((r) => r.type === t);
      byType[t][s] = rs.length ? pct(rs, (r) => covered(s, r)) : null; // null = not measured for this kind of site
    }
  }

  const repeat = results.repeat ?? {};
  const stable = (list) => (list?.length ? { n: list.length, sameEveryTime: list.filter((x) => x.distinct === 1).length, avgDistinct: round(mean(list.map((x) => x.distinct)), 2) } : null);

  const failures = [];
  for (const s of systems) {
    for (const r of rowsOf(results, s)) if (!covered(s, r)) failures.push({ system: s, id: r.id, type: r.type, why: (r.errors ?? []).join("; ").slice(0, 160) || (r.keywordCoverage !== undefined && r.ok ? `only ${Math.round(r.keywordCoverage * 100)}% of the key words appear` : "not served") });
  }

  return {
    systems,
    rows,
    byType,
    repeat: { sparcOffline: stable(repeat.sparcOffline), geminiPlan: stable(repeat.geminiPlan), ai: stable(repeat.ai) },
    failures,
    levels: results.levels ?? [],
  };
}

const f = (v, unit = "") => (v === null || v === undefined ? "n/a" : `${v}${unit}`);
const table = (head, body) => [`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...body.map((r) => `| ${r.join(" | ")} |`)].join("\n");

export function renderReport(results) {
  const a = aggregate(results);
  const m = results.meta ?? {};
  const L = [];
  L.push("# Phase 8: evaluation report");
  L.push("");
  L.push(`Generated by \`npm run registry:evaluate-sites\`. Run date: ${m.finishedAt ?? m.startedAt ?? "unknown"}. AI model: ${m.model ?? "unknown"}. Requests: ${m.requests ?? "?"}.`);
  L.push("");
  L.push("## What was compared");
  L.push("");
  L.push("The same 30 website requests (`sparc/eval/requests.json`: 12 admin portals, 6 portfolios, 6 landing pages, 3 online stores, 3 booking sites) were built three ways:");
  L.push("");
  L.push("- **(a) Templates only.** How the prototype worked: a fixed template per website type, and for a portal the preset modules of the chosen industry. A request is served only if a template exists for its type and, for a portal, the preset already contains every module the request needs.");
  L.push("- **(b) SPARC.** Plan the site, choose verified library components, assemble a project, run the checks and a real Vite build. Run twice: with the offline planner (no key needed) and with the Gemini planner.");
  L.push("- **(c) AI writes all the code.** One Gemini call writes the whole site as a single React file, which is wrapped in the smallest project that can build it. One attempt only, no repair.");
  L.push("");
  L.push(`A site **covers** a request when its own checks pass and at least ${COVER_MIN * 100}% of the request's key words appear in it. For (b) the words are searched in the site's config (names, labels, headings); for (c) in the code.`);
  L.push("");

  const total = m.requests ?? 0;
  const missing = ["sparc-gemini", "ai-code"].filter((s) => !a.systems.includes(s) || a.rows[s].n < total);
  if (missing.length || m.gemini?.available === false) {
    L.push("## Not measured in this run");
    L.push("");
    L.push(`Gemini could not be used for part of this run${m.gemini?.reason ? ` (${m.gemini.reason})` : ""}. Those parts are **not measured**, and are not counted as failures of the system:`);
    L.push("");
    for (const s of missing) L.push(`- ${SYSTEM_LABELS[s]}: ${a.rows[s] ? `${a.rows[s].n} of ${total} requests measured` : `0 of ${total} requests measured`}.`);
    L.push("");
    L.push("When the Gemini quota is available again, run `npm run registry:evaluate-sites -- --resume` and then `npm run registry:evaluate-report`. Finished work is kept; only the missing parts run.");
    L.push("");
  }

  L.push("## Headline results");
  L.push("");
  L.push(
    table(
      ["System", "Requests measured", "Own checks pass", "Builds", "Covers the request", "Website type right", "Avg time (s)", "Avg AI tokens", "Avg new lines written", "Reused (%)"],
      a.systems.map((s) => {
        const r = a.rows[s];
        return [r.label, `${r.n} of ${total}`, f(r.ownChecksPct, "%"), f(r.buildsPct, "%"), f(r.coveredPct, "%"), f(r.typeCorrectPct, "%"), r.avgSeconds, r.avgTokens, r.avgNewLines, r.avgReusePct];
      })
    )
  );
  L.push("");
  L.push("Words used here: **own checks** = for SPARC, the config checklist plus a real build; for AI code, the build; for templates, the preset has every module needed. **New lines written** = lines a person or the AI had to produce for this one site (for SPARC that is the config, never code).");
  L.push("");

  L.push("## By kind of website (requests covered, %)");
  L.push("");
  L.push(table(["Website type", "Requests", ...a.systems.map((s) => SYSTEM_LABELS[s])], Object.entries(a.byType).map(([t, v]) => [t, v.n, ...a.systems.map((s) => f(v[s], "%"))])));
  L.push("");

  L.push("## Errors and security findings");
  L.push("");
  L.push("The same simple code scanner (`registry/evaluation/metrics.js`) was run over the code each system produced for every site: images without alt text, inputs without a label or id, `dangerouslySetInnerHTML`, `eval`, hard-coded secrets, plain `http://` calls and stray `console.log`. It is a heuristic, not a full audit.");
  L.push("");
  L.push(
    table(
      ["System", "Findings per site", "Sites with a finding", "Accessibility", "Security", "Lint"],
      a.systems
        .filter((s) => s !== "templates")
        .map((s) => {
          const r = a.rows[s];
          return [r.label, r.findingsPerSite, f(r.sitesWithFindings, "%"), r.kindsTotal.accessibility ?? 0, r.kindsTotal.security ?? 0, r.kindsTotal.lint ?? 0];
        })
    )
  );
  L.push("");
  L.push("SPARC's scan includes the shared library and shell code copied into each site, so its count is for the whole site, not only the new part.");
  L.push("");

  L.push("## Same answer every time");
  L.push("");
  const rp = a.repeat;
  const line = (name, x, what) => (x ? `- **${name}:** ${x.sameEveryTime} of ${x.n} requests gave ${what} on all 3 runs (average ${x.avgDistinct} different results per request).` : `- **${name}:** not measured in this run.`);
  L.push(line("SPARC, offline planner", rp.sparcOffline, "the identical site (config and component versions)"));
  L.push(line("SPARC + Gemini planner", rp.geminiPlan, "the identical plan (type, industry, modules)"));
  L.push(line("AI writes all the code", rp.ai, "byte-identical code"));
  L.push("");

  L.push("## Size at each style level");
  L.push("");
  L.push("The same site built at every style level it allows. Sizes are what the browser downloads (JavaScript and CSS, gzip).");
  L.push("");
  const levelRows = a.levels.filter((x) => x.ok !== false);
  L.push(table(["Website type", "Style", "Download (KB gzip)", "Raw (KB)", "Build (ms)", "Components"], levelRows.map((x) => [x.websiteType, x.styleLevel, x.gzipKb, x.rawKb, x.buildMs, x.components])));
  L.push("");
  L.push("Lighthouse scores were **not** run (they need a real browser and network settings); download size is the speed measure used here.");
  L.push("");

  L.push("## Search and planner quality");
  L.push("");
  if (results.search) {
    L.push(`- Component search on ${results.search.n} labelled queries: Recall@5 = ${results.search.recallAt5}, MRR = ${results.search.mrr}.`);
  }
  if (results.planner) {
    const p = results.planner;
    L.push(`- Planner on ${p.n} labelled descriptions: website type ${p.websiteTypeAccuracy}, industry ${p.industryAccuracy}, config valid ${p.configValidPct}, module recall ${p.moduleRecall}, module precision ${p.modulePrecision}.`);
  }
  L.push("");

  L.push("## Requests a system did not cover");
  L.push("");
  const fails = a.failures.filter((x) => x.system !== "templates");
  L.push(fails.length ? table(["System", "Request", "Type", "Why"], fails.map((x) => [SYSTEM_LABELS[x.system], x.id, x.type, x.why || "n/a"])) : "None for SPARC or AI code.");
  const tFails = a.failures.filter((x) => x.system === "templates");
  L.push("");
  L.push(`Templates-only could not serve ${tFails.length} of ${a.rows.templates?.n ?? 0} requests (${[...new Set(tFails.map((x) => x.type))].join(", ") || "none"}).`);
  L.push("");

  L.push("## What this does and does not show");
  L.push("");
  L.push("- It does **not** include the user study (people rating the four style levels). The protocol and the analysis script are ready (`docs/eval/USER_STUDY.md`, `registry/evaluation/ratings.js`); the ratings have to come from real people.");
  L.push("- \"Covers the request\" is a word check, not a human judgement of quality. It cannot tell a good design from a bad one.");
  L.push("- The AI-code system got one attempt with one prompt and one model. A person would retry on a build error; a better prompt or model would raise its numbers. Treat its numbers as a baseline for a single try.");
  L.push("- Time and token numbers depend on the day's Gemini load (retries are counted in `results.json`).");
  L.push("- The templates-only baseline is a model of the prototype's rules (template exists for the type, industry preset has the modules), not a run of the old pages by hand.");
  L.push("- Everything is one run on one machine. The raw numbers for every request are in `docs/eval/results.json`.");
  L.push("");
  return `${L.join("\n")}\n`;
}


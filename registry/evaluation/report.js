const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);
const COLORS = ["var(--c1)", "var(--c2)", "var(--c3)", "var(--c4)"];

/** Horizontal bar chart. bars: [{label, value, color?}]. */
export function barChart({ title, unit = "", bars, max }) {
  const top = max ?? Math.max(1, ...bars.map((b) => b.value));
  const rowH = 34;
  const labelW = 210;
  const w = 640;
  const h = bars.length * rowH + 16;
  const items = bars
    .map((b, i) => {
      const bw = Math.max(1, ((w - labelW - 90) * b.value) / top);
      const y = 8 + i * rowH;
      return `<g><text x="0" y="${y + 18}" class="lbl">${esc(b.label)}</text><rect x="${labelW}" y="${y + 3}" width="${bw}" height="20" rx="3" fill="${b.color ?? COLORS[i % COLORS.length]}"/><text x="${labelW + bw + 8}" y="${y + 18}" class="val">${esc(b.value)}${esc(unit)}</text></g>`;
    })
    .join("");
  return `<figure><figcaption>${esc(title)}</figcaption><svg viewBox="0 0 ${w} ${h}" role="img" aria-label="${esc(title)}">${items}</svg></figure>`;
}

export function renderCharts(results) {
  const a = aggregate(results);
  const bySystem = (field, unit, title, max) => barChart({ title, unit, max, bars: a.systems.map((s, i) => ({ label: a.rows[s].label, value: a.rows[s][field] ?? 0, color: COLORS[i % COLORS.length] })) });
  const levels = a.levels.filter((x) => x.ok !== false);
  const levelCharts = [...new Set(levels.map((x) => x.websiteType))]
    .map((t) => barChart({ title: `Download size by style level: ${t} (KB gzip)`, unit: " KB", bars: levels.filter((x) => x.websiteType === t).map((x, i) => ({ label: x.styleLevel, value: x.gzipKb, color: COLORS[i % COLORS.length] })) }))
    .join("\n");
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>SPARC AI evaluation charts</title>
<style>
:root{--bg:#ffffff;--fg:#0f172a;--muted:#475569;--card:#f8fafc;--border:#e2e8f0;--c1:#64748b;--c2:#2563eb;--c3:#0d9488;--c4:#d97706}
@media (prefers-color-scheme: dark){:root:not([data-theme="light"]){--bg:#0b1120;--fg:#e2e8f0;--muted:#94a3b8;--card:#111a2e;--border:#1e293b;--c1:#94a3b8;--c2:#60a5fa;--c3:#2dd4bf;--c4:#fbbf24}}
:root[data-theme="dark"]{--bg:#0b1120;--fg:#e2e8f0;--muted:#94a3b8;--card:#111a2e;--border:#1e293b;--c1:#94a3b8;--c2:#60a5fa;--c3:#2dd4bf;--c4:#fbbf24}
body{margin:0;background:var(--bg);color:var(--fg);font:16px/1.5 system-ui,sans-serif}
main{max-width:760px;margin:0 auto;padding:24px 16px 48px}
h1{font-size:1.5rem;margin:0 0 4px}p{color:var(--muted);margin:0 0 20px}
figure{margin:0 0 20px;padding:16px;background:var(--card);border:1px solid var(--border);border-radius:10px}
figcaption{font-weight:600;margin-bottom:8px}
svg{width:100%;height:auto;display:block}.lbl,.val{fill:var(--fg);font-size:13px}.val{fill:var(--muted)}
</style>
</head>
<body>
<main>
<h1>SPARC AI evaluation</h1>
<p>${esc(results.meta?.requests ?? "?")} website requests, built three ways. Details: docs/EVALUATION.md.</p>
${bySystem("coveredPct", "%", "Requests fully covered (checks pass and key words present)", 100)}
${bySystem("avgSeconds", " s", "Average time per site (seconds)")}
${bySystem("avgTokens", "", "Average AI tokens per site")}
${bySystem("avgNewLines", "", "Average new lines written per site")}
${bySystem("findingsPerSite", "", "Scanner findings per site (lower is better)")}
${levelCharts}
</main>
</body>
</html>
`;
}


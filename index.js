// ---------------------------------------------------------------------------
// POST /api/deploy
// Body: { repoName, owner }
// 1) Ensure Vercel project exists (create with Vite build settings, or fetch existing)
// 2) Trigger a production deployment from GitHub main
// 3) Poll deployment status until READY / ERROR / timeout
// ---------------------------------------------------------------------------
app.post("/api/deploy", async (req, res) => {
  const { repoName, owner } = req.body || {};
  console.log("\n[deploy] request:", { repoName, owner });

  const token = process.env.VERCEL_TOKEN;
  const teamId = process.env.VERCEL_TEAM_ID || undefined;

  // --- Token check first ---
  if (!token) {
    console.error("[deploy] VERCEL_TOKEN missing from environment");
    return res.status(500).json({
      success: false,
      error: "Server missing VERCEL_TOKEN. Set it in server/.env. See .env.example.",
    });
  }

  // --- Input validation ---
  if (!repoName || !owner) {
    return res.status(400).json({ success: false, error: "repoName and owner are required" });
  }
  if (!NAME_RE.test(repoName)) {
    return res.status(400).json({ success: false, error: "repoName must be alphanumeric, dash, or underscore" });
  }

  // Vercel requires project names lowercase.
  const projectName = repoName.toLowerCase();

  try {
    // --- 1. Ensure project exists with correct Vite build settings ---
    console.log("[deploy] ensuring Vercel project:", projectName);
    let project;
    try {
      project = await vercelFetch("/v10/projects", {
        method: "POST",
        token,
        teamId,
        body: {
          name: projectName,
          framework: "vite",
          buildCommand: "npm run build",
          outputDirectory: "dist",
          installCommand: "npm install",
          devCommand: "npm run dev",
          gitRepository: {
            type: "github",
            repo: `${owner}/${repoName}`,
          },
        },
      });
      console.log("[deploy] project created:", project.id);
    } catch (err) {
      // Project already exists -> fetch it.
      if (err.status === 409 || /already exists/i.test(err.message || "")) {
        console.log("[deploy] project exists, fetching:", projectName);
        project = await vercelFetch(`/v9/projects/${projectName}`, { token, teamId });
      } else if (
        err.status === 400 &&
        /repository|not found|access/i.test(err.message || "")
      ) {
        return res.status(400).json({
          success: false,
          error:
            "Vercel can't access this GitHub repo. Install the Vercel GitHub app for your account: https://vercel.com/dashboard -> Add New -> Project. Then retry.",
        });
      } else {
        throw err;
      }
    }

    // Vercel returns the GitHub repo's id in project.link after connection.
    const repoId = project?.link?.repoId;
    if (!repoId) {
      return res.status(500).json({
        success: false,
        error:
          "Vercel project has no linked GitHub repoId. The Vercel-GitHub integration may not be installed for this account/repo.",
      });
    }

    // --- 2. Trigger a production deployment from GitHub main ---
    console.log("[deploy] creating deployment from github main");
    const deployment = await vercelFetch("/v13/deployments", {
      method: "POST",
      token,
      teamId,
      body: {
        name: project.name,
        project: project.id,
        target: "production",
        gitSource: {
          type: "github",
          repoId,
          ref: "main",
        },
      },
    });
    console.log("[deploy] deployment queued:", deployment.id, "url:", deployment.url);

    // --- 3. Poll until READY / ERROR / CANCELED / timeout ---
    const TIMEOUT_MS = 120_000; // 2 minutes
    const POLL_MS = 3000;
    const start = Date.now();
    let final = deployment;
    let lastState = final.readyState || "QUEUED";

    while (Date.now() - start < TIMEOUT_MS) {
      await new Promise((r) => setTimeout(r, POLL_MS));
      final = await vercelFetch(`/v13/deployments/${deployment.id}`, { token, teamId });
      lastState = final.readyState || final.status || "UNKNOWN";
      console.log("[deploy]   poll state:", lastState);

      if (lastState === "READY") break;
      if (lastState === "ERROR" || lastState === "CANCELED") {
        return res.status(500).json({
          success: false,
          error: `Vercel build ${lastState}. Check the build logs at https://vercel.com/${owner}/${projectName}/deployments`,
          status: lastState,
        });
      }
    }

    const previewUrl = `https://${final.url || deployment.url}`;
    const deploymentUrl = `https://${projectName}.vercel.app`;
    console.log("[deploy] done:", deploymentUrl, "(state:", lastState + ")");

    return res.json({
      success: true,
      deploymentUrl,
      previewUrl,
      status: lastState,
      message:
        lastState === "READY"
          ? "Deployment is live."
          : "Deployment started — may still be building. Refresh in a moment.",
    });
  } catch (err) {
    console.error("[deploy] error:", err);
    return res.status(500).json({ success: false, error: err.message || "Unknown deploy error" });
  }
});


// POST /api/generate-config
// Body: { description: string, templateId: string }
// Turn a free-text description into validated content.json via Gemini.
//   - rate limited: 10 req / IP / hour
//   - cached: same description within 1h returns the cached config
//   - one retry if the model returns non-JSON
// ---------------------------------------------------------------------------

// In-memory cache: sha256(description) -> { config, expires }. Cleared on restart.
const CONFIG_CACHE = new Map();
const CACHE_TTL_MS = 60 * 60 * 1000; // 1 hour

function cacheKey(description) {
  return crypto.createHash("sha256").update(description).digest("hex");
}


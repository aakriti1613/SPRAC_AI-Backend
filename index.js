// 10 requests per IP per hour.
const generateConfigLimiter = rateLimit({
  windowMs: 60 * 60 * 1000,
  max: 10,
  standardHeaders: true,
  legacyHeaders: false,
  message: { success: false, error: "Rate limit exceeded: 10 requests per hour. Try again later." },
});

// Call Gemini once and return the parsed JSON object (throws on parse failure).
async function callGemini(ai, description, { retry = false } = {}) {
  const userText = retry
    ? `Your previous output was not valid JSON. Output ONLY valid JSON.\n\nDescription:\n${description}`
    : description;

  const response = await ai.models.generateContent({
    model: process.env.GEMINI_MODEL || "gemini-2.5-flash",
    contents: userText,
    config: {
      systemInstruction: PORTFOLIO_SYSTEM_PROMPT,
      responseMimeType: "application/json",
    },
  });

  const text = response.text ?? "";
  return JSON.parse(text); // may throw -> caller decides retry vs 500
}

app.post("/api/generate-config", generateConfigLimiter, async (req, res) => {
  const { description, templateId } = req.body || {};
  const resolvedTemplateId = validateResolvedTemplateId(templateId);
  console.log("\n[generate-config] request received:", {
    templateId,
    resolvedTemplateId,
    descriptionLength: typeof description === "string" ? description.length : 0,
  });

  // --- Input validation ---
  if (!description || typeof description !== "string" || !description.trim()) {
    return res.status(400).json({ success: false, error: "description (non-empty string) is required" });
  }
  if (!templateId || !resolvedTemplateId) {
    return res.status(400).json({ success: false, error: "templateId missing or invalid" });
  }

  // --- API key check ---
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    console.error("[generate-config] GEMINI_API_KEY missing from environment");
    return res.status(500).json({
      success: false,
      error: "Server missing GEMINI_API_KEY. Set it in server/.env. See .env.example.",
    });
  }

  // --- Cache check ---
  const key = cacheKey(description.trim());
  const cached = CONFIG_CACHE.get(key);
  if (cached && cached.expires > Date.now()) {
    console.log("[generate-config] cache HIT ->", key.slice(0, 12));
    return res.json({
      success: true,
      config: cached.config,
      warnings: cached.warnings || [],
      cached: true,
    });
  }
  if (cached) CONFIG_CACHE.delete(key); // expired
  console.log("[generate-config] cache MISS ->", key.slice(0, 12));

  try {
    const ai = new GoogleGenAI({ apiKey });

    // --- AI call (+ one retry on bad JSON) ---
    let parsed;
    try {
      console.log("[generate-config] AI call: gemini-2.5-flash");
      parsed = await callGemini(ai, description.trim());
      console.log("[generate-config] parse: OK");
    } catch (parseErr) {
      console.warn("[generate-config] parse failed, retrying once:", parseErr.message);
      try {
        parsed = await callGemini(ai, description.trim(), { retry: true });
        console.log("[generate-config] parse: OK (after retry)");
      } catch (retryErr) {
        console.error("[generate-config] retry parse failed:", retryErr.message);
        return res.status(500).json({
          success: false,
          error: "AI did not return valid JSON after retry. Try rephrasing the description.",
        });
      }
    }

    // --- Validate / sanitize ---
    console.log("[generate-config] validate: cleaning config");
    const { config: validatedConfig, warnings } = validatePortfolioConfigWithWarnings(parsed);

    // --- Cache + respond ---
    CONFIG_CACHE.set(key, { config: validatedConfig, warnings, expires: Date.now() + CACHE_TTL_MS });
    console.log("[generate-config] respond: success");
    return res.json({ success: true, config: validatedConfig, warnings });
  } catch (err) {
    console.error("[generate-config] error:", err);
    return res.status(500).json({ success: false, error: err.message || "Unknown error generating config" });
  }
});


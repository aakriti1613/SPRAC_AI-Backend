async function ensureDemoPortal() {
  await fs.ensureDir(PORTALS_DIR);
  const entries = await fs.readdir(PORTALS_DIR);
  if (entries.length > 0) return;

  const config = demoPortalConfig();
  await fs.outputJson(portalConfigPath(config.slug), config, { spaces: 2 });
  const data = demoPortalData();
  for (const [entity, records] of Object.entries(data)) {
    await fs.outputJson(portalDataPath(config.slug, entity), records, { spaces: 2 });
  }
  console.log(`[server] seeded demo portal: ${config.slug}`);
}

try {
  await ensureDemoPortal();
} catch (err) {
  console.error("[server] demo portal seed failed:", err);
}


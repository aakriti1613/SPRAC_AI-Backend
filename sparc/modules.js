/** Validate the library once at import: unique ids, known field types, real list columns. */
const seen = new Set();
for (const m of MODULE_LIBRARY) {
  if (seen.has(m.id)) throw new Error(`duplicate module id "${m.id}"`);
  seen.add(m.id);
  const keys = new Set(m.fields.map((x) => x.key));
  if (keys.size !== m.fields.length) throw new Error(`module "${m.id}" has duplicate field keys`);
  for (const field of m.fields) {
    if (!FIELD_TYPE_NAMES.includes(field.type)) throw new Error(`module "${m.id}" field "${field.key}" has unknown type "${field.type}"`);
  }
  for (const c of m.listColumns) if (!keys.has(c)) throw new Error(`module "${m.id}" list column "${c}" is not a field`);
}

export const MODULE_IDS = MODULE_LIBRARY.map((m) => m.id);

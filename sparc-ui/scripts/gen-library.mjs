// Generates the level wrappers and the per-level registries.
//
//   library/<room>/<level>/sparc/index.tsx       = view (_views) + skin (_skins)
//   library/form-field/<level>/<id>/index.tsx    = field view + skin (Basic, Good)
//   shells/<shell>/src/registries/<level>.ts     = which component fills each room
//
// One wrapper per V1 target slot (from ../sparc libraryTargets). Registries pick,
// for every room, the best component at or below the requested level (so a
// workflow room that only has Basic/Good uses Good on an Amazing site).
//
//   node scripts/gen-library.mjs           write files
//   node scripts/gen-library.mjs --check   exit 1 if anything is out of date
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const UI = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const HEADER = "// GENERATED by scripts/gen-library.mjs: edit the view (library/_views) or skin (library/_skins), not this file.";
const LEVELS = ["basic", "good", "amazing", "astonishing"];
const SKIN = { basic: "basicSkin", good: "goodSkin", amazing: "amazingSkin", astonishing: "astonishingSkin" };
const SHELLS = {
  "portal-shell": { blueprints: ["admin-portal"], max: "amazing" },
  "site-shell": { blueprints: ["portfolio", "landing", "ecommerce", "booking"], max: "astonishing" },
};

const pascal = (id) => id.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const fieldViews = () =>
  fs.readdirSync(path.join(UI, "library", "_views", "form-field")).filter((f) => f.endsWith(".tsx")).map((f) => f.replace(/\.tsx$/, "")).sort();

function fieldTypesOf(id) {
  const text = fs.readFileSync(path.join(UI, "library", "_views", "form-field", `${id}.tsx`), "utf8");
  const m = /export const fieldTypes = (\[[^\]]*\]) as const;/.exec(text);
  if (!m) throw new Error(`_views/form-field/${id}.tsx has no "export const fieldTypes = [...] as const"`);
  return JSON.parse(m[1]);
}

function roomWrapper(room, level) {
  const props = `${pascal(room)}Props`;
  const name = `${pascal(room)}${pascal(level)}`;
  return `${HEADER}
import type { ${props} } from "@contracts";
import View from "../../../_views/${room}";
import { SkinProvider } from "../../../_skins/context";
import { ${SKIN[level]} } from "../../../_skins/${level}";

export default function ${name}(props: ${props}) {
  return (
    <SkinProvider skin={${SKIN[level]}}>
      <View {...props} />
    </SkinProvider>
  );
}
`;
}

function fieldWrapper(id, level) {
  const types = fieldTypesOf(id);
  return `${HEADER}
import type { FormFieldProps } from "@contracts";
import View from "../../../_views/form-field/${id}";
import { SkinProvider } from "../../../_skins/context";
import { ${SKIN[level]} } from "../../../_skins/${level}";

export const fieldTypes = ${JSON.stringify(types)} as const;

export default function ${pascal(id)}${pascal(level)}(props: FormFieldProps) {
  return (
    <SkinProvider skin={${SKIN[level]}}>
      <View {...props} />
    </SkinProvider>
  );
}
`;
}

function registryFile(shell, level, rooms, available) {
  const order = LEVELS.slice(0, LEVELS.indexOf(level) + 1).reverse();
  const pick = (room) => order.find((l) => available.has(`${room}/${l}`));
  const imports = [];
  const entries = [];
  for (const room of rooms) {
    if (room === "form-field") continue;
    const l = pick(room);
    if (!l) throw new Error(`${shell}: no component for room "${room}" at or below ${level}`);
    const ident = `${pascal(room)}${pascal(l)}`;
    imports.push(`import ${ident} from "@library/${room}/${l}/sparc";`);
    entries.push(`    ${/^[a-z]+$/.test(room) ? room : JSON.stringify(room)}: ${ident},`);
  }
  const fieldLines = [];
  if (rooms.includes("form-field")) {
    const fl = pick("form-field");
    for (const id of fieldViews()) {
      const ident = `F${pascal(id)}`;
      imports.push(`import * as ${ident} from "@library/form-field/${fl}/${id}";`);
      fieldLines.push(ident);
    }
  }
  return `${HEADER}
// Registry for ${shell} at style level "${level}". The assembler (Phase 5) writes one of these per generated site.
import type { SlotRegistry } from "@core/slots";
${fieldLines.length ? 'import { fieldMap } from "@core/slots";\n' : ""}
${imports.sort().join("\n")}

export const registry: SlotRegistry = {
  styleLevel: "${level}",
  rooms: {
${entries.join("\n")}
  },
  fields: ${
    fieldLines.length
      ? `fieldMap(\n    [${fieldLines.join(", ")}].map((m) => ({ component: m.default, fieldTypes: m.fieldTypes }))\n  )`
      : "{}"
  },
};
`;
}

/** Every file this script owns: { relativePath: content }. */
export async function plan() {
  const { libraryTargets, loadBlueprints } = await import("../../sparc/index.js");
  const blueprints = loadBlueprints();
  const files = {};
  const available = new Set();
  for (const row of libraryTargets(blueprints).rows) {
    for (const level of row.levels) {
      available.add(`${row.room}/${level}`);
      if (row.room === "form-field") {
        for (const id of fieldViews()) files[`library/form-field/${level}/${id}/index.tsx`] = fieldWrapper(id, level);
      } else {
        files[`library/${row.room}/${level}/sparc/index.tsx`] = roomWrapper(row.room, level);
      }
    }
  }
  for (const [shell, { blueprints: ids, max }] of Object.entries(SHELLS)) {
    const rooms = [...new Set(blueprints.filter((b) => ids.includes(b.id)).flatMap((b) => [...b.rooms.required, ...b.rooms.optional]))].sort();
    for (const level of LEVELS.slice(0, LEVELS.indexOf(max) + 1)) {
      files[`shells/${shell}/src/registries/${level}.ts`] = registryFile(shell, level, rooms, available);
    }
  }
  return files;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const files = await plan();
  let stale = 0;
  for (const [rel, content] of Object.entries(files)) {
    const abs = path.join(UI, rel);
    const current = fs.existsSync(abs) ? fs.readFileSync(abs, "utf8") : null;
    if (current === content) continue;
    stale += 1;
    if (check) console.log("out of date:", rel);
    else {
      fs.mkdirSync(path.dirname(abs), { recursive: true });
      fs.writeFileSync(abs, content);
    }
  }
  console.log(`${Object.keys(files).length} generated files, ${stale} ${check ? "out of date" : "written"}`);
  process.exit(check && stale ? 1 : 0);
}
